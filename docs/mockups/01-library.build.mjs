const HERE = path.dirname(new URL(import.meta.url).pathname);
const OUTDIR = process.env.MOCKUP_OUT || HERE;

const esc = s => String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
// The date a student in Sydney would read, from the attempt's own timestamp.
const day = iso => {
  const p = new Intl.DateTimeFormat("en-AU", { timeZone: "Australia/Sydney", day: "numeric", month: "numeric" })
    .formatToParts(new Date(iso));
  return p.find(x => x.type === "day").value + " " + MONTHS[Number(p.find(x => x.type === "month").value) - 1];
};
const plural = (n, w) => n + " " + w + (n === 1 ? "" : "s");
const ROMAN = ["I", "II", "III", "IV", "V", "VI"];

// ---- the paper, as the contract reads it ---------------------------------
const cur = ASSESS.curriculumOf(paper);
if (!cur || !cur.course) throw new Error("the paper no longer declares a course");
const totals = PAPER.totals(paper);
const identity = [cur.course, cur.stage].filter(Boolean).join(" · ");
const facts = [plural(totals.questions, "question"), plural(paper.sections.length, "section"),
               plural(totals.marks, "mark"), paper.time].filter(Boolean).join(" · ");

// ---- one paper card, in whichever status its attempt is in ------------------
function card(a) {
  const sections = a.whole ? "" :
    `<p class="scope">Sections ${a.sections.map(i => ROMAN[i]).join(", ").replace(/, ([^,]*)$/, " and $1")} only</p>`;
  let status, actions;
  if (a.status === "not_started") {
    status = `<span class="state">Not started</span>`;
    actions = `<a class="btn" href="#overview">Start paper</a>`;
  } else if (a.status === "in_progress") {
    const pct = Math.round(100 * a.answered / a.total);
    status = `<span class="state live">In progress</span>
      <p class="count"><b>${a.answered} of ${a.total}</b> answered${a.flagged ? ` · <span class="flagged">⚑ ${a.flagged} flagged</span>` : ""}${a.notMarked ? ` · ${a.notMarked} not marked` : ""}</p>
      <div class="pbar" role="progressbar" aria-label="Answered" aria-valuemin="0" aria-valuemax="${a.total}" aria-valuenow="${a.answered}"><i style="width:${pct}%"></i></div>
      <p class="sub"><b>${a.got}/${a.max}</b> marks so far · saved ${day(a.updatedAt)}</p>`;
    actions = `<a class="btn" href="#resume">Resume paper</a>
      <p class="where">Picks up at Question ${esc(a.current.display)}</p>`;
  } else {
    status = `<span class="state done">Completed ${day(a.completedAt)}</span>
      <p class="score"><b>${a.got}</b> / ${a.max}</p>
      <p class="sub">${a.answered} of ${a.total} answered${a.notMarked ? ` · ${a.notMarked} not marked` : ""}</p>`;
    actions = `<a class="btn" href="#results">View results</a>
      <a class="btn ghost" href="#overview">Try again</a>`;
  }
  return `<article class="paper" aria-labelledby="p1">
    <div class="who">
      <p class="kicker">${esc(identity)}</p>
      <h2 id="p1"><a href="#overview">${esc(paper.name)}</a></h2>
      <p class="facts">${esc(facts)}</p>
      ${sections}
    </div>
    <div class="status">${status}</div>
    <div class="acts">${actions}
      <button class="del" type="button">Delete paper</button>
    </div>
  </article>`;
}

